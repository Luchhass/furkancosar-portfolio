function countBy(projects, key) {
  return projects.reduce((acc, project) => {
    const value = project[key] || "Uncategorized";
    acc[value] = (acc[value] || 0) + 1;

    return acc;
  }, {});
}

function countNested(projects, key) {
  return projects.reduce((acc, project) => {
    project[key]?.forEach((value) => {
      acc[value] = (acc[value] || 0) + 1;
    });

    return acc;
  }, {});
}

function createProjectStats(projects) {
  return {
    total: projects.length,
    featured: projects.filter((project) => project.featured).length,
    completed: projects.filter((project) => project.status === "Completed")
      .length,
    categories: countBy(projects, "category"),
    types: countBy(projects, "type"),
    statuses: countBy(projects, "status"),
    technologies: countNested(projects, "technologies"),
    tags: countNested(projects, "tags"),
  };
}

